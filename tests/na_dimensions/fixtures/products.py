def list_card(product: dict) -> dict:
    return {
        "asin": product["asin"],
        "title": product["title"],
        "price": product["price"],
        "price_value": product["price_value"],
        "rating": product["rating"],
        "review_count": product["review_count"],
        "image_url": f"https://m.media-amazon.com/images/I/{product['asin']}.jpg",
    }


def detail_fields(product: dict) -> dict:
    keys = [
        "asin", "title", "price_value", "rating", "review_count",
        "date_first_available", "bsr_main_rank", "bsr_main_category",
        "bsr_sub_rank", "bsr_sub_category", "item_weight", "weight_lb",
        "item_dimensions", "dim_l_in", "dim_w_in", "dim_h_in",
        "variant_option_count", "other_sellers_count", "fba_fee",
        "fulfillment_type", "country_of_origin", "is_amazon_choice", "is_bestseller",
    ]
    return {k: product.get(k) for k in keys}


